"""
Implemetation of Thing Model.

Thing Descriptions are always generated by the specific protocols.
"""

from __future__ import annotations

import json

from collections.abc import ItemsView
from typing import Any, Optional

from pydantic import ConfigDict, Field

from hololinked.core.interfaces import Metadata
from hololinked.metadata.td.base import WoTSchema
from hololinked.metadata.td.interaction_affordance import (
    ActionAffordance,
    EventAffordance,
    PropertyAffordance,
)
from hololinked.metadata.td.metadata import VersionInfo
from hololinked.metadata.td.utils import a_class_name_from_title_string, model_spec_has_extensions


from hololinked.core import Thing  # noqa  # isort: skip


class ThingModel(WoTSchema, Metadata):
    """
    Thing Model as per W3C WoT Thing Description v1.1.

    - [Specification](https://www.w3.org/TR/wot-thing-description11/)
    - [UML Diagram](https://docs.hololinked.dev/UML/PDF/ThingModel.pdf)
    """

    context: list[str | dict[str, str]] = Field(["https://www.w3.org/2022/wot/td/v1.1"], alias="@context")
    type: Optional[str | list[str]] = None
    id: Optional[str] = None
    title: Optional[str] = None
    description: Optional[str] = None
    version: Optional[VersionInfo] = None
    created: Optional[str] = None
    modified: Optional[str] = None
    support: Optional[str] = None
    base: Optional[str] = None
    properties: dict[str, PropertyAffordance] = Field(default_factory=dict)
    actions: dict[str, ActionAffordance] = Field(default_factory=dict)
    events: dict[str, EventAffordance] = Field(default_factory=dict)

    model_config = ConfigDict(extra="allow")

    def __init__(
        self,
        thing: Thing | None = None,
        allow_loose_schema: Optional[bool] = False,
        ignore_errors: bool = False,
        skip_names: Optional[list[str]] = [],
    ) -> None:
        WoTSchema.__init__(self)
        Metadata.__init__(
            self,
            thing=thing,
            ignore_errors=ignore_errors,
            skip_names=skip_names,
        )
        self.allow_loose_schema = allow_loose_schema

    def generate(self) -> ThingModel:
        """
        Populate the thing model.

        Returns
        -------
        ThingModel

        Raises
        ------
        ValueError
            If the thing instance is not attached to the thing model. Usually, when API first approach is used,
            the thing instance could not yet be instantiated. This method is not to be used at that time.
        """
        if self.thing is None:
            raise ValueError("Thing Model instance not attached to a Thing instance to generate metadata.")
        self.id = self.thing.id
        self.title = self.thing.__class__.__name__
        self.context = ["https://www.w3.org/2022/wot/td/v1.1"]
        # default value of context is not being picked up although we only use exclude_unset=True
        if self.thing.__doc__:
            self.description = WoTSchema.format_doc(self.thing.__doc__)
        source = getattr(type(self.thing), "_thing_model", None)  # the model a Thing produced from it implements
        if source is not None:
            self.title = source.title or self.title
            self.description = source.description
        self.properties = {}
        self.actions = {}
        self.events = {}
        self.add_interaction_affordances()
        return self

    def produce(self, impl: Any, id: str, validator: str = "pydantic", **kwargs: Any) -> Thing:
        """
        Create a `Thing` instance based on the Thing Model, possibly binding with an existing implementation object `impl`.

        Members of the `impl` must implement the interactions by name:
        - a method must implement an action
        - a `property` must be implemented as a plain attribute or a python `property` descriptor

        Events do not have a mapping and are created based on the Thing Model definition, accessible at runtime.

        If custom objects implement properties and actions, use the `property_impl` and `action_impl` keyword arguments
        to provide the corresponding implementation objects.

        Parameters
        ----------
        impl: Any
            the object implementing the Thing Model, can be `None`.
        id: str
            id of the `Thing`
        validator: str
            validator type for payloads, usually pydantic for pydantic models
        **kwargs: Any
            Additional keyword arguments:

            - `member_names_map` - an explicit mapping of interaction name to the member implementing it, only for names
            that differ (by default every interaction is implemented by the member of the same name)
            - `property_impl` - optional, if you have not implemented a getattr in your implementation class,
            you can provide an object that handles property access. default `@property` descriptors or custom
            descriptors do not require that you provide this. Names like `get()`, `set()`, and `delete()` are handled
            automatically. For other names, use `property_impl_fget`, `property_impl_fset`, and `property_impl_fdel`
            as needed.
            - `action_impl` - optional, if you have not implemented a standard method for an action in your
            implementation class, you can provide an object that handles action calls. default methods on the
            implementation object do not require that you provide this.
            - `property_impl_fget` - optional, if you have not implemented a getattr in your implementation class,
            you can provide an object that handles property access. default `@property` descriptors or custom
            descriptors with __get__ do not require that you provide this.
            -  `property_impl_fset` - optional, if you have not implemented a setattr in your implementation class,
            you can provide an object that handles property setting. default `@property` descriptors or custom
            descriptors with __set__ do not require that you provide this.
            - `property_impl_fdel` - optional, if you have not implemented a delattr in your implementation class,
            you can provide an object that handles property deletion. default `@property` descriptors or custom
            descriptors with __delete__ do not require that you provide this.
            - `action_impl_call` - optional, if you have not implemented a standard method for an action in your
            implementation class, you can provide an object that handles action calls. default methods on the
            implementation object do not require that you provide this.
            - `thing_kwargs` - any other argument of the `Thing` object

        Returns
        -------
        Thing
            the created `Thing`

        Raises
        ------
        ConformanceError
            listing every member that does not match the Thing Model
        """
        member_names_map = dict(kwargs.pop("member_names_map", None) or {})
        descriptors = Metadata.compile_descriptors_from(
            model=self,
            impl=impl,
            member_names_map=member_names_map,
            validator=validator,
            property_impl=kwargs.pop("property_impl", None),
            action_impl=kwargs.pop("action_impl", None),
        )
        namespace = {**descriptors, "_thing_model": self, "__doc__": self.description}
        # create the class with the namespace
        class_def = type(a_class_name_from_title_string(self.title), (Thing,), namespace)
        thing = class_def(id=id, **kwargs.pop("thing_kwargs", {}))
        # update the delegates if any
        for descriptor in descriptors.values():
            if descriptor.delegate is not None:
                descriptor.delegate.thing = thing

        return thing

    @classmethod
    def from_metadata(cls, metadata: dict[str, Any]) -> ThingModel:
        """
        Convert a JSON specification of a Thing Description or a Thing Model into a ThingModel instance.

        Parameters
        ----------
        metadata: dict[str, Any]
            the Thing Description or Thing Model JSON

        Returns
        -------
        ThingModel
            the model with its properties, actions and events, not attached to a Thing instance

        Raises
        ------
        NotImplementedError
            if the Thing Model uses `tm:ref` or `{{placeholders}}`, which are not supported yet
        """
        if model_spec_has_extensions(metadata):
            raise NotImplementedError("Thing Models with tm:ref or {{placeholders}} are not supported yet")
        model = cls()
        for key in ("id", "title", "description", "created", "modified", "support", "base"):
            if key in metadata:
                setattr(model, key, metadata[key])
        if "@context" in metadata:
            context = metadata["@context"]
            model.context = context if isinstance(context, list) else [context]
        model.properties = {
            name: PropertyAffordance.from_metadata(name, metadata) for name in metadata.get("properties", {})
        }
        model.actions = {name: ActionAffordance.from_metadata(name, metadata) for name in metadata.get("actions", {})}
        model.events = {name: EventAffordance.from_metadata(name, metadata) for name in metadata.get("events", {})}
        return model

    @classmethod
    def from_file(cls, path: str) -> ThingModel:
        """
        Load a Thing Description or a plain Thing Model from a JSON file.

        Parameters
        ----------
        path: str
            path of the JSON file

        Returns
        -------
        ThingModel
            the model with its properties, actions and events, not attached to a Thing instance
        """
        with open(path, encoding="utf-8") as file:
            return cls.from_metadata(json.load(file))

    # not the best code and logic, but works for now
    skip_properties: list[str] = ["expose", "thing_description", "GUI", "object_info"]
    """list of property names to skip when generating the TD"""

    skip_actions: list[str] = [
        Thing._add_property.name,
        Thing._get_properties.name,
        Thing._get_properties_in_db.name,
        Thing._set_properties.name,
        "get_postman_collection",
        "get_our_thing_model",
    ]
    """list of action names to skip when generating the TD"""

    skip_events: list[str] = []
    """list of event names to skip when generating the TD"""

    def add_interaction_affordances(self) -> None:
        """
        Add interaction affordances to the thing model.

        Raises
        ------
        ValueError
            If the thing instance is not attached to the thing model. Usually, when API first approach is used,
            the thing instance could not yet be instantiated. This method is not to be used at that time.
        """
        if self.thing is None:
            raise ValueError("Thing Model instance not attached to a Thing instance to generate metadata.")
        affordances: list[
            tuple[str, ItemsView[str, Any], type[PropertyAffordance | ActionAffordance | EventAffordance], list[str]]
        ] = [
            ("properties", self.thing.properties.remote_objects.items(), PropertyAffordance, self.skip_properties),
            ("actions", self.thing.actions.descriptors.items(), ActionAffordance, self.skip_actions),
            ("events", self.thing.events.plain.items(), EventAffordance, self.skip_events),
        ]
        for affordance, items, affordance_cls, skip_list in affordances:
            for name, obj in items:
                if name in skip_list or name in self.skip_names:
                    continue
                if name == "state" and affordance == "properties" and not hasattr(self.thing, "state_machine"):
                    continue
                try:
                    affordance_dict = getattr(self, affordance)
                    affordance_dict[name] = affordance_cls.from_descriptor(obj, self.thing)
                except Exception as ex:
                    if not self.ignore_errors:
                        raise ex from None
                    if hasattr(self.thing, "logger"):
                        self.thing.logger.error(f"Error while generating schema for {name} - {ex}")

    def model_dump(self, **kwargs) -> dict[str, Any]:
        """
        Return the JSON representation.

        Returns
        -------
        dict[str, Any]
            JSON representation
        """

        def dump_value(value):
            nonlocal kwargs
            if hasattr(value, "model_dump"):
                return value.model_dump(**kwargs)
            elif isinstance(value, dict):
                return {k: dump_value(v) for k, v in value.items()}
            elif isinstance(value, list):
                return [dump_value(v) for v in value]
            elif isinstance(value, tuple):
                return tuple(dump_value(v) for v in value)
            else:
                return value

        result = {}
        for field in self.__class__.model_fields:
            if field in self.skip_keys:
                continue
            if not hasattr(self, field) or getattr(self, field) is None:
                continue
            if field in [
                "instance",
                "skip_keys",
                "skip_properties",
                "skip_actions",
                "skip_events",
                "skip_names",
                "ignore_errors",
                "allow_loose_schema",
            ]:
                continue
            value = getattr(self, field)
            result[field] = dump_value(value)
        return result
